// THE CORRECTION LETTER (owner 2026-11-27, brief javito-level-20261127, ADR-XXXX).
//
// Between 11-13 and 11-23 fifty cold letters went out with a mock whose opening picture came from the old town
// picker: a locomotive (Zalaegerszeg M62, Vasvár M41), a railway / bus station, a space photo (ISS „View of Earth”).
// Since 11-24 no such mock goes out (the curated town library, ADR-0479). The owner's decision: every lead who
// LOOKED at such a mock gets one correction letter with two new plans by today's generator — but only after he has
// seen the old and the new side by side and pressed „Mehet” lead by lead.
//
// A RULE, NOT SEVEN HAND STEPS (CLAUDE.md §2c):
//   ① select   — a sent prospect whose main or second plan carries a town picture matching FAULTY_TOWN_PICTURE,
//                with at least one non-bot view, not unsubscribed (address level), no reply of any kind (a reply
//                is doubtful: the owner left Hajnalka out for an empty one), not blocked, not a customer
//                → one `fix_letter` row per lead (UNIQUE lead_id: once per lead, ever).
//   ② prepare  — both plans regenerated by the current engine from the old plan's own curated words (the chain's
//                generatePlan, no copy-writer call, $0), both through the machine render gate; a new prospect (own
//                token, own link) carries them. A plan that cannot be made / fails the gate → held with the reason.
//   ③ decide   — the owner's „Mehet” stamps his yes on both plan files (ownerApproval) → approved;
//                „Nem mehet ki” → rejected, closed.
//   ④ send     — sendOutreachMail(prospect, { fixLetter }) — the guarded send path with every send-time check;
//                the letter text is the owner's (fixLetterCopy.ts).
