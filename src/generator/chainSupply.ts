interface GateRetry {
  readonly n: number;
  readonly step: "photos" | "template";
  readonly at: string;
  readonly codes: readonly string[];
  readonly excluded?: readonly string[];
  readonly from?: string;
}

function gateRetryOf(inputs: unknown): GateRetry | null {
  const g = (inputs as { gateRetry?: GateRetry } | null)?.gateRetry;
  return g && typeof g.n === "number" ? g : null;
}

/** The curated words of a plan as a curator pack (the second-plan step's reading of inputs.copyManual). */
export function curatedFieldsOf(inputs: unknown): Record<string, unknown> | null {
  const cm = ((inputs as { copyManual?: Record<string, { value?: unknown }> } | null)?.copyManual ?? {}) as Record<string, { value?: unknown }>;
  const fields: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(cm)) if (v && typeof v === "object" && "value" in v) fields[k] = v.value;
  return Object.keys(fields).length ? fields : null;
}

function templateOf(inputs: unknown): string | null {
  return ((inputs as { recipe?: { template?: unknown } } | null)?.recipe?.template as string | undefined) ?? null;
}

/**
 * Generate a plan for the lead in `template` with `fields` (curated words). A thin lead that cannot open a gate gets the
 * other allowed template not in `avoid` (the second-plan step's rule, owner 2026-11-07). Returns the new artifact id.
 */
async function generatePlan(leadId: string, template: string, fields: Record<string, unknown>, avoid: ReadonlySet<string>): Promise<{ id: string; template: string }> {
  const loaded = await loadLead(leadId);
  // The template the engine ACTUALLY rendered: a lead with no photo and no town picture always gets the Névből növő
  // (generateEngine noPhotoHero), whatever was asked — measured 11-27 on the blind sample (13/24).
  const gen = async (t: string) => {
    const r = await generateEngineMock(loaded, undefined, { template: t, curatorCopy: { fields: fields as never, by: CHAIN_SUPPLY_BY } });
    const row = await db.selectFrom("mock_artifact").select("inputs").where("id", "=", r.artifactId).executeTakeFirst();
    return { id: r.artifactId, template: templateOf(row?.inputs) ?? t };
  };
  try {
    return await gen(template);
  } catch (e) {
    // wordmark-grow first (it needs no gate photo), the Parallax last.
    const other = ["wordmark-grow", "parallax"].find((t) => t !== template && !avoid.has(t) && OWNER_ALLOWED_TEMPLATES.has(t));
    if (template !== "gate-opening" || !other || !/Kapunyitás/.test((e as Error).message)) throw e;
    return gen(other);
  }
}

/**
 * The old plan's approval and Vera PASS move to the new plan ONLY when the new plan's words hash to the old words
 * (byte-equal copy). Returns what carried over.
 */
export async function carryApproval(oldId: string, newId: string): Promise<{ review: boolean; approved: boolean; reason: string }> {
  const [o, n] = await Promise.all([
    db.selectFrom("mock_artifact").select(["status", "inputs"]).where("id", "=", oldId).executeTakeFirst(),
    db.selectFrom("mock_artifact").select(["status", "inputs"]).where("id", "=", newId).executeTakeFirst(),
  ]);
  if (!o || !n) return { review: false, approved: false, reason: "hiányzó mock" };
  const oh = copyHashOf(o.inputs);
  const nh = copyHashOf(n.inputs);
  if (!oh || !nh || oh !== nh) return { review: false, approved: false, reason: `a szöveg nem bájtra azonos (${oh?.slice(0, 8) ?? "-"} ≠ ${nh?.slice(0, 8) ?? "-"})` };
  let review = false;
  if (reviewStateOf(o.inputs) === "pass") {
    const r = reviewOf(o.inputs);
    await recordReview(newId, { verdict: "pass", by: r?.by ?? CHAIN_SUPPLY_BY, ref: r?.ref ?? `mock ${oldId.slice(0, 8)}`, note: `átvéve a ${oldId.slice(0, 8)} tervről: bájtra azonos szöveg (lánc-utánpótlás)` });
    review = true;
  }
  let approved = false;
  if (o.status === "approved" && review) {
    await curateArtifact(newId, "approve", `átvéve a ${oldId.slice(0, 8)} tervről: bájtra azonos szöveg`, CHAIN_SUPPLY_BY);
    approved = true;
  }
  return { review, approved, reason: review ? "átvéve" : "a régi terven nem volt érvényes Vera-PASS" };
}

async function retire(oldId: string, newId: string): Promise<void> {
  const o = await db.selectFrom("mock_artifact").select("status").where("id", "=", oldId).executeTakeFirst();
  if (o && o.status !== "rejected") await curateArtifact(oldId, "reject", `superseded_by:${newId} (lánc-utánpótlás)`, CHAIN_SUPPLY_BY);
}

export interface RegenOutcome {
  readonly leadId: string;
  readonly ok: boolean;
  readonly note: string;
  readonly mainId?: string;
  readonly altId?: string;
}

/**
 * ① One waiting row: both plans regenerated from the main plan's words; the row points at the new main plan and waits
 * for the machine gate again. The old plans are retired (superseded), never deleted.
 */
export async function regenerateRow(dispatchId: string): Promise<RegenOutcome> {
  const d = await db.selectFrom("outreach_dispatch").select(["lead_id", "artifact_id", "status", "note"]).where("id", "=", dispatchId).executeTakeFirst();
  if (!d?.artifact_id) return { leadId: d?.lead_id ?? "", ok: false, note: "nincs sor / mock" };
  const leadId = d.lead_id;
  const main = await db.selectFrom("mock_artifact").select(["id", "inputs", "status"]).where("id", "=", d.artifact_id).executeTakeFirst();
  if (!main) return { leadId, ok: false, note: "a fő terv hiányzik" };
  const alt = await secondPlanOf(leadId, main.id).catch(() => null);
  const altRow = alt ? await db.selectFrom("mock_artifact").select(["id", "inputs"]).where("id", "=", alt.id).executeTakeFirst() : null;
  const fields = curatedFieldsOf(main.inputs) ?? curatedFieldsOf(altRow?.inputs);
  if (!fields) return { leadId, ok: false, note: "a terven nincs kurátori szöveg (copyManual) — írót kér, nem gépi lépés" };
  const oldMainT = templateOf(main.inputs);
  const mainT = oldMainT && OWNER_ALLOWED_TEMPLATES.has(oldMainT) ? oldMainT : "parallax";
  const newMain = await generatePlan(leadId, mainT, fields, new Set());
  const oldAltT = templateOf(altRow?.inputs);
  const altT = oldAltT && OWNER_ALLOWED_TEMPLATES.has(oldAltT) && oldAltT !== newMain.template
    ? oldAltT
    : (parseInt(leadId.slice(0, 2), 16) % 2 ? "gate-opening" : "wordmark-grow") !== newMain.template
      ? (parseInt(leadId.slice(0, 2), 16) % 2 ? "gate-opening" : "wordmark-grow")
      : "wordmark-grow" !== newMain.template ? "wordmark-grow" : "gate-opening";
  let newAlt: { id: string; template: string };
  try {
    newAlt = await generatePlan(leadId, altT, fields, new Set([newMain.template]));
  } catch (e) {
    // No half offer left behind: the new main plan goes too, the row keeps its old plans and is held with the reason.
    await curateArtifact(newMain.id, "reject", `a 2. terv nem készült el: ${(e as Error).message.slice(0, 200)}`, CHAIN_SUPPLY_BY);
    throw e;
  }
  if (newAlt.template === newMain.template) {
    // No second plan is possible (no own photo, no town picture: every template renders as the Névből növő). The offer
    // needs two (owner 2026-11-25), so nothing new is kept and the row is held with the reason — never a one-plan letter.
    for (const id of [newMain.id, newAlt.id]) await curateArtifact(id, "reject", "egyforma sablon: kép nélkül nincs második terv", CHAIN_SUPPLY_BY);
    return { leadId, ok: false, note: `kép és településkép nélkül mindkét terv ${newMain.template} lett — második terv nem készülhet` };
  }
  await carryApproval(main.id, newMain.id);
  if (altRow) await carryApproval(altRow.id, newAlt.id);
  // The row follows its new main plan, back to the machine gate (the owner's old yes was on another file).
  await db
    .updateTable("outreach_dispatch")
    .set({ artifact_id: newMain.id, status: "held", note: QA_WAIT_NOTE })
    .where("id", "=", dispatchId)
    .where("status", "in", ["queued", "held"])
    .execute();
  await retire(main.id, newMain.id);
  if (altRow) await retire(altRow.id, newAlt.id);
  return { leadId, ok: true, note: `újragenerálva: ${newMain.template} + ${newAlt.template}`, mainId: newMain.id, altId: newAlt.id };
}

/** ① The timer's step: the oldest-generator waiting rows, a budget at a time — a half-done offer first, then own photos, the town pages last. */
export async function regenerateOldQueue(budgetMs: number, limit = 20): Promise<{ done: number; failed: number; left: number }> {
  const started = Date.now();
  const base = db
    .selectFrom("outreach_dispatch as d")
    .innerJoin("mock_artifact as a", "a.id", "d.artifact_id")
    .innerJoin("lead as l", "l.id", "d.lead_id")
    .where(WAITING_SQL)
    .where(LEAD_HAS_EMAIL_SQL)
    .where(sql<boolean>`a.generated_at < ${MOCK_MIN_GENERATED_AT}::timestamptz`)
    .where("l.lifecycle_status", "<>", "disqualified");
  const rows = await base
    .select(["d.id as id"])
    // own photos before the town pages, and within that the countries' turns with a half-done offer first (FAIR_ORDER)
    .orderBy(sql`(${LEAD_OWN_PHOTOS_SQL} >= ${LEAD_MIN_OWN_PHOTOS_SQL}) desc`)
    .orderBy(FAIR_ORDER)
    .limit(limit)
    .execute();
  let done = 0;
  let failed = 0;
  for (const r of rows) {
    if (Date.now() - started > budgetMs || !boxHasRoom()) break;
    try {
      const o = await regenerateRow(r.id);
      if (o.ok) done++;
      else {
        failed++;
        // Not a machine step any more: the row leaves the loop with the reason (a writer has to give it words).
        await db.updateTable("outreach_dispatch").set({ status: "held", note: `lánc-utánpótlás: ${o.note}`.slice(0, 500) }).where("id", "=", r.id).where("status", "in", ["queued", "held"]).execute();
      }
      console.log(`  ${o.ok ? "↻" : "⚠️"} ${o.leadId.slice(0, 8)} ${o.note}`); // i18n-exempt: operator log
    } catch (e) {
      failed++;
      // Out of the loop with the reason: a generation that throws (no gate photo, a closed place, a country without a
      // layer row) throws again next firing — never regenerate the same lead every five minutes.
      await db.updateTable("outreach_dispatch").set({ status: "held", note: `lánc-utánpótlás: az újragenerálás hibára futott — ${(e as Error).message}`.slice(0, 500) }).where("id", "=", r.id).where("status", "in", ["queued", "held"]).execute();
      console.warn(`  ⚠️ újragenerálás ${r.id.slice(0, 8)}: ${(e as Error).message.slice(0, 200)}`); // i18n-exempt: operator log
    }
  }
  const left = await base.select(db.fn.countAll().as("n")).executeTakeFirst();
  return { done, failed, left: Number(left?.n ?? 0) };
}

/** ③ Ready mocks without a dispatch row → a held row with the chain-wait note (enqueueDispatch's refusals stand). */
export async function enqueueReadyWithoutRow(limit = 200): Promise<{ queued: number; refused: number }> {
  const rows = await db
    .selectFrom("lead as l")
    .innerJoin("mock_artifact as a", "a.lead_id", "l.id")
    .select(["l.id as leadId", "a.id as artifactId", "a.inputs as inputs"])
    .where("a.status", "=", "approved")
    .where(sql<boolean>`a.inputs->>'reviewVerdict' = 'pass'`)
    .where(sql<string>`a.inputs->'recipe'->>'template'`, "in", [...OWNER_ALLOWED_TEMPLATES])
    .where("l.qualification", "in", ["no_site", "outdated"])
    .where("l.lifecycle_status", "<>", "disqualified")
    .where("l.contact_block_at", "is", null)
    .where(sql<boolean>`coalesce(l.raw->>'email', '') <> ''`)
    // The own-site gate stands (a „no site” lead with a found site or a suspicious one gets no letter).
    .where(sql<boolean>`(l.qualification <> 'no_site' or coalesce(l.raw->'ownSiteCheck'->>'verdict', '') = 'NINCS')`)
    .where(sql<boolean>`not exists (select 1 from outreach_dispatch d where d.lead_id = l.id)`)
    .orderBy(sql`(${LEAD_OWN_PHOTOS_SQL} >= ${LEAD_MIN_OWN_PHOTOS_SQL}) desc`)
    .orderBy("a.generated_at", "desc")
    .limit(limit)
    .execute();
  let queued = 0;
  let refused = 0;
  const seen = new Set<string>();
  for (const r of rows) {
    if (seen.has(r.leadId)) continue;
    seen.add(r.leadId);
    // The PASS must be on today's words (a stale copy hash = no review).
    if (reviewStateOf(r.inputs) !== "pass") continue;
    const q = await enqueueDispatch({ leadId: r.leadId, artifactId: r.artifactId, by: CHAIN_SUPPLY_BY });
    if (q.ok) {
      await db.updateTable("outreach_dispatch").set({ status: "held", note: QA_WAIT_NOTE }).where("id", "=", q.id).execute();
      queued++;
    } else refused++;
  }
  return { queued, refused };
}

/** ⑤ What to try for a failed plan, from its findings and its counted tries. Pure — the rule the step and the check share. */
export function retryPlanFor(
  gate: Pick<RenderGateResult, "verdict" | "findings">,
  tries: { readonly planPhoto: number; readonly lead: number; readonly templateLeft: boolean },
): { readonly step: "photos"; readonly exclude: readonly string[] } | { readonly step: "template" } | { readonly step: "hold"; readonly reason: string } {
  if (gate.verdict !== "fail") return { step: "hold", reason: "nem bukott" };
  const reason = gate.findings.slice(0, 3).map((f) => f.detail).join(" · ");
  if (gate.findings.some((f) => f.code === "render")) return { step: "hold", reason: `renderelési hiba (a kapu újramér): ${reason}` };
  if (tries.lead >= GATE_RETRY_LEAD_MAX) return { step: "hold", reason };
  const photoOnly = gate.findings.every((f) => PHOTO_CODES.has(f.code));
  const exclude = [...new Set(gate.findings.map((f) => f.url).filter((u): u is string => typeof u === "string" && /^https?:/i.test(u)))];
  if (photoOnly && exclude.length && tries.planPhoto < GATE_RETRY_PHOTO_MAX) return { step: "photos", exclude };
  if (tries.templateLeft) return { step: "template" };
  return { step: "hold", reason };
}

async function mtimeOf(rel: string | null): Promise<number | null> {
  if (!rel) return null;
  const { stat } = await import("node:fs/promises");
  try {
    return Math.floor((await stat(path.resolve(process.cwd(), rel))).mtimeMs / 1000);
  } catch {
    return null;
  }
}

/**
 * ⑤ One failed plan of a waiting row: re-allot its photos without the named pictures, or re-make it in the lead's unused
 * allowed template with the same words, or hold the row with the reason. Returns what was done.
 */
export async function retryFailedPlan(dispatchId: string, planId: string): Promise<string> {
  const d = await db.selectFrom("outreach_dispatch").select(["lead_id", "artifact_id"]).where("id", "=", dispatchId).executeTakeFirst();
  const plan = await db.selectFrom("mock_artifact").select(["id", "lead_id", "path", "inputs", "generated_at", "status"]).where("id", "=", planId).executeTakeFirst();
  if (!d || !plan) return "nincs";
  const mtime = await mtimeOf(plan.path);
  const gate = mtime == null ? null : cachedRenderGate(plan.inputs, mtime, (plan.inputs as { renderGate?: { stockOk?: boolean } }).renderGate?.stockOk ?? true);
  if (!gate || gate.verdict !== "fail") return "nincs friss bukás";
  const plans = await db.selectFrom("mock_artifact").select(["id", "inputs"]).where("lead_id", "=", d.lead_id).execute();
  const leadTries = plans.reduce((s, p) => s + (gateRetryOf(p.inputs)?.n ?? 0), 0);
  const own = gateRetryOf(plan.inputs);
  const live = await db.selectFrom("mock_artifact").select("inputs").where("lead_id", "=", d.lead_id).where("status", "<>", "rejected").execute();
  const used = new Set(live.map((p) => templateOf(p.inputs)).filter((t): t is string => !!t));
  const triedTemplates = new Set(plans.map((p) => templateOf(p.inputs)).filter((t): t is string => !!t));
  const freeTemplate = [...OWNER_ALLOWED_TEMPLATES].find((t) => !used.has(t) && !triedTemplates.has(t)) ?? null;
  const plan5 = retryPlanFor(gate, { planPhoto: own?.step === "photos" ? own.n : 0, lead: leadTries, templateLeft: freeTemplate != null });
  const codes = [...new Set(gate.findings.map((f) => f.code))];
  let step = plan5;
  if (step.step === "photos") {
    // A lead with its own photos must keep the country's minimum on the page, else the photo rule holds it forever.
    const now = ((plan.inputs as { siteData?: { photos?: { url: string }[] } } | null)?.siteData?.photos ?? []);
    const drop = new Set(step.exclude.map((u) => sizelessPhotoKey(u)));
    const keep = now.filter((p) => !drop.has(sizelessPhotoKey(p.url))).length;
    if (now.length >= DEFAULT_MIN_OWN_PHOTOS && keep < DEFAULT_MIN_OWN_PHOTOS) step = freeTemplate ? { step: "template" } : { step: "hold", reason: "a hibás képek nélkül kevés saját kép marad" };
    // a town page whose town hero is out and no other judged town picture is left cannot be re-allotted
    const sdIn = (plan.inputs as { siteData?: { townPhoto?: { url: string }; townGallery?: { url: string }[] } } | null)?.siteData;
    if (step.step === "photos" && sdIn?.townPhoto && drop.has(sizelessPhotoKey(sdIn.townPhoto.url)) && !(sdIn.townGallery ?? []).some((g) => !drop.has(sizelessPhotoKey(g.url)))) {
      const lead = (await loadLead(plan.lead_id)).lead;
      const town = await townPhotosForMock({ leadId: plan.lead_id, city: lead.city, country: await countryOfLead(plan.lead_id), lat: lead.lat, lon: lead.lon, email: lead.email, ownPhotos: now }).catch(() => null);
      const left = [...(town?.hero ? [town.hero] : []), ...(town?.gallery ?? [])].filter((g) => !drop.has(sizelessPhotoKey(g.url)));
      if (!left.length) step = { step: "hold", reason: "a településnek nincs más jóváhagyott képe a nyitóképre (town_photo_set)" };
    }
  }
  if (step.step === "photos") {
    const plan5 = step;
    type Pic = { url: string };
    const inputs = structuredClone((plan.inputs ?? {}) as Record<string, unknown>) as Record<string, unknown> & {
      siteData?: { photos?: Pic[]; townPhoto?: Pic; townGallery?: Pic[] };
    };
    const drop = new Set(plan5.exclude.map((u) => sizelessPhotoKey(u)));
    const keep = (p: Pic) => !drop.has(sizelessPhotoKey(p.url));
    const sd = inputs.siteData;
    if (sd) {
      sd.photos = (sd.photos ?? []).filter(keep);
      // A TOWN picture is a picture too (11-27 blind sample: 15 of 21 fails were the town hero): it leaves the page, and
      // the town gallery's next judged picture (same picker stamp) opens it; none left → the template step next time.
      if (sd.townGallery) sd.townGallery = sd.townGallery.filter(keep);
      if (sd.townPhoto && !keep(sd.townPhoto)) {
        // the town's CURRENT judged set (the generator's own reader, townHero.townPhotosForMock) — its hero and
        // gallery without the failed pictures; the page's own gallery as the last resort
        const lead = (await loadLead(plan.lead_id)).lead;
        const town = await townPhotosForMock({ leadId: plan.lead_id, city: lead.city, country: await countryOfLead(plan.lead_id), lat: lead.lat, lon: lead.lon, email: lead.email, ownPhotos: sd.photos }).catch(() => null);
        const fresh = [...(town?.hero ? [town.hero] : []), ...(town?.gallery ?? [])].filter(keep) as Pic[];
        const next = fresh.shift() ?? sd.townGallery?.shift();
        if (next) {
          sd.townPhoto = next;
          if (fresh.length) sd.townGallery = fresh;
        } else delete sd.townPhoto;
      }
    }
    const excluded = [...new Set([...(own?.excluded ?? []), ...plan5.exclude])];
    inputs.gateRetry = { n: (own?.step === "photos" ? own.n : 0) + 1, step: "photos", at: new Date().toISOString(), codes, excluded } satisfies GateRetry;
    await refreshMock({ id: plan.id, lead_id: plan.lead_id, path: plan.path, inputs, generated_at: plan.generated_at }, { backupDir: path.resolve(process.cwd(), "sites/_mock-refresh-backup") });
    await db.updateTable("outreach_dispatch").set({ status: "held", note: QA_WAIT_NOTE }).where("id", "=", dispatchId).where("status", "in", ["queued", "held"]).execute();
    return `képek újraosztva (${plan5.exclude.length} kép ki)`;
  }
  if (step.step === "template" && freeTemplate) {
    const fields = curatedFieldsOf(plan.inputs) ?? curatedFieldsOf(live.find((p) => curatedFieldsOf(p.inputs))?.inputs);
    if (!fields) return hold(dispatchId, "nincs kurátori szöveg a másik sablonhoz");
    const others = new Set([...used].filter((t) => t !== templateOf(plan.inputs)));
    const made = await generatePlan(d.lead_id, freeTemplate, fields, others);
    if (others.has(made.template)) {
      await curateArtifact(made.id, "reject", "a másik sablon a meglévő tervvel egyezett (kép nélkül csak Névből növő)", CHAIN_SUPPLY_BY);
      return hold(dispatchId, `nincs más sablon: ${gate.findings.slice(0, 2).map((f) => f.detail).join(" · ")}`);
    }
    await db
      .updateTable("mock_artifact")
      .set({ inputs: sql`jsonb_set(inputs, '{gateRetry}', ${JSON.stringify({ n: 1, step: "template", at: new Date().toISOString(), codes, from: plan.id } satisfies GateRetry)}::jsonb)` as never })
      .where("id", "=", made.id)
      .execute();
    await carryApproval(plan.id, made.id);
    const isMain = d.artifact_id === plan.id;
    await db
      .updateTable("outreach_dispatch")
      .set({ ...(isMain ? { artifact_id: made.id } : {}), status: "held", note: QA_WAIT_NOTE })
      .where("id", "=", dispatchId)
      .where("status", "in", ["queued", "held"])
      .execute();
    await retire(plan.id, made.id);
    return `másik sablon: ${made.template}`;
  }
  return hold(dispatchId, step.step === "hold" ? step.reason : "nincs több próba");
}

async function hold(dispatchId: string, reason: string): Promise<string> {
  await db.updateTable("outreach_dispatch").set({ status: "held", note: `${GATE_EXHAUSTED_PREFIX} ${reason}`.slice(0, 1000) }).where("id", "=", dispatchId).where("status", "in", ["queued", "held"]).execute();
  return `tartva: ${reason.slice(0, 120)}`;
}

/** ⑤ The timer's step: every waiting row's plan whose current verdict is a fail — a half-done offer first. */
export async function retryFailedQueue(budgetMs: number, limit = 20): Promise<{ tried: number; held: number }> {
  const started = Date.now();
  const rows = await db
    .selectFrom("outreach_dispatch as d")
    .innerJoin("mock_artifact as a", "a.id", "d.artifact_id")
    .innerJoin("lead as l", "l.id", "d.lead_id")
    .select(["d.id as dispatchId", "d.lead_id as leadId", "d.artifact_id as mainId", "a.inputs as inputs"])
    .where(WAITING_SQL)
    .where(LEAD_HAS_EMAIL_SQL)
    .where(MOCK_CURRENT_GENERATOR_SQL)
    .orderBy(FAIR_ORDER)
    .execute();
  const failedNow = (inputs: unknown): boolean => {
    const g = (inputs as { renderGate?: RenderGateResult } | null)?.renderGate;
    return g?.version === RENDER_GATE_VERSION && g.verdict === "fail" && !g.findings.some((f) => f.code === "render");
  };
  const work: { dispatchId: string; planId: string; half: boolean }[] = [];
  for (const r of rows) {
    const alt = await secondPlanOf(r.leadId, r.mainId).catch(() => null);
    const altIn = alt ? (await db.selectFrom("mock_artifact").select("inputs").where("id", "=", alt.id).executeTakeFirst())?.inputs : null;
    const mainFail = failedNow(r.inputs);
    const altFail = alt ? failedNow(altIn) : false;
    const pass = (i: unknown) => (i as { renderGate?: RenderGateResult } | null)?.renderGate?.verdict === "pass";
    if (mainFail) work.push({ dispatchId: r.dispatchId, planId: r.mainId, half: pass(altIn) });
    else if (alt && altFail) work.push({ dispatchId: r.dispatchId, planId: alt.id, half: pass(r.inputs) });
  }
  work.sort((a, b) => Number(b.half) - Number(a.half));
  let tried = 0;
  let held = 0;
  for (const w of work.slice(0, limit)) {
    if (Date.now() - started > budgetMs || !boxHasRoom()) break;
    try {
      const what = await retryFailedPlan(w.dispatchId, w.planId);
      if (what.startsWith("tartva")) held++;
      else tried++;
      console.log(`  ⟲ ${w.planId.slice(0, 8)} ${what}`); // i18n-exempt: operator log
    } catch (e) {
      console.warn(`  ⚠️ újrapróba ${w.planId.slice(0, 8)}: ${(e as Error).message.slice(0, 200)}`); // i18n-exempt: operator log
      await hold(w.dispatchId, `az újrapróba hibára futott: ${(e as Error).message.slice(0, 200)}`);
      held++;
    }
  }
  return { tried, held };
}
